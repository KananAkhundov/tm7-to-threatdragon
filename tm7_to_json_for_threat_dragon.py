#!/usr/bin/env python3
"""Convert Microsoft Threat Modeling Tool .tm7 files to Threat Dragon 2.6.x JSON.

Uses only the Python standard library. Conversion is best-effort: Microsoft
stencil-specific attributes that have no direct Threat Dragon equivalent are
not guaranteed to round-trip. Always review the generated diagram and threats.
"""
import argparse
import json
import sys
import uuid
import xml.etree.ElementTree as ET
from pathlib import Path


def local(tag):
    return tag.rsplit("}", 1)[-1]


def child(element, name):
    if element is None:
        return None
    return next((e for e in list(element) if local(e.tag) == name), None)


def child_text(element, name, default=""):
    found = child(element, name)
    return found.text if found is not None and found.text is not None else default


def number(element, name, default=0.0):
    try:
        return float(child_text(element, name, str(default)))
    except (TypeError, ValueError):
        return default


def as_bool(value):
    return str(value).strip().lower() in ("true", "1", "yes")

def clean_name(value):
    return " ".join((value or "").split())

def display_properties(element):
    """Read Microsoft display properties by their user-facing DisplayName."""
    result = {}
    props = child(element, "Properties")
    if props is None:
        return result
    for prop in list(props):
        label = (child_text(prop, "DisplayName") or child_text(prop, "Key")).strip()
        value_node = child(prop, "Value")
        value = value_node.text if value_node is not None and value_node.text is not None else ""
        if label:
            result[label] = value
    return result


def make_ports():
    groups, items = {}, []
    for side in ("top", "right", "bottom", "left"):
        groups[side] = {
            "position": side,
            "attrs": {"circle": {
                "r": 4, "magnet": True, "stroke": "#5F95FF",
                "strokeWidth": 1, "fill": "#fff",
                "style": {"visibility": "hidden"}
            }}
        }
        items.append({"group": side, "id": str(uuid.uuid4())})
    return {"groups": groups, "items": items}


def get_port(ports, side):
    return next((item["id"] for item in ports["items"] if item["group"] == side), ports["items"][0]["id"])


def nearest_side(x, y, node):
    dx, dy = x - node["cx"], y - node["cy"]
    if abs(dx) >= abs(dy):
        return "right" if dx >= 0 else "left"
    return "bottom" if dy >= 0 else "top"


def make_node(shape, name, x, y, width, height, data, z, include_ports=True):
    cell = {
        "position": {"x": round(x), "y": round(y)},
        "size": {"width": round(width), "height": round(height)},
        "attrs": {
            "text": {"text": name},
            "body": {"stroke": "#333333", "strokeWidth": 1.5, "strokeDasharray": None}
        },
        "visible": True,
        "shape": shape,
        "id": str(uuid.uuid4()),
        "zIndex": z,
        "data": data
    }
    if include_ports:
        cell["ports"] = make_ports()
    return cell


def make_flow(name, source, target, sx, sy, tx, ty, handle_x, handle_y, data, z):
    source_side = nearest_side(sx, sy, source)
    target_side = nearest_side(tx, ty, target)
    flow = {
        "shape": "flow",
        "attrs": {"line": {
            "stroke": "#333333",
            "targetMarker": {"name": "block"},
            "sourceMarker": {"name": ""},
            "strokeDasharray": None
        }},
        "width": 200,
        "height": 100,
        "zIndex": z,
        "connector": "smooth",
        "data": data,
        "labels": [name],
        "id": str(uuid.uuid4()),
        "source": {"cell": source["node"]["id"], "port": get_port(source["ports"], source_side)},
        "target": {"cell": target["node"]["id"], "port": get_port(target["ports"], target_side)}
    }
    # Microsoft stores a routing handle for most connectors. Preserve it so
    # parallel arrows do not all collapse onto the same straight path.
    if handle_x is not None and handle_y is not None:
        flow["vertices"] = [{"x": round(handle_x), "y": round(handle_y)}]
    return flow


def threat_type(category):
    normalized = " ".join((category or "").replace("_", " ").split()).lower()
    mapping = {
        "spoofing": "Spoofing",
        "tampering": "Tampering",
        "repudiation": "Repudiation",
        "information disclosure": "Information Disclosure",
        "denial of service": "Denial of Service",
        "elevation of privilege": "Elevation of Privilege",
    }
    return mapping.get(normalized, category or "Other")


def threat_status(state):
    s = (state or "").strip().lower()
    if s == "mitigated":
        return "Mitigated"
    if "not applicable" in s or "notapplicable" in s:
        return "Not Applicable"
    # AutoGenerated is Microsoft's threat-generation state, not a mitigation
    # status. Threat Dragon should show these as open/unresolved threats.
    return "Open"


def parse_threats(root, guid_to_flow, guid_to_node, report):
    threats_by_cell = {}
    threat_number = 0
    total = 0
    for collection in root.iter():
        if local(collection.tag) != "ThreatInstances":
            continue
        for entry in list(collection):
            value = child(entry, "Value")
            if value is None:
                continue
            total += 1
            props = display_properties(value)
            state = child_text(value, "State")
            state_info = (props.get("StateInformation") or child_text(value, "StateInformation")).strip()
            category = threat_type(props.get("UserThreatCategory", "") or child_text(value, "UserThreatCategory"))
            title = (props.get("Title") or child_text(value, "Title") or "Unnamed threat").strip()
            description = (props.get("UserThreatDescription") or child_text(value, "UserThreatDescription") or "").strip()
            short_description = (props.get("UserThreatShortDescription") or child_text(value, "UserThreatShortDescription") or "").strip()
            if not description:
                description = short_description
            priority = (props.get("Priority") or child_text(value, "Priority") or "Medium").strip().title()
            if priority not in ("High", "Medium", "Low", "Critical"):
                priority = "Medium"
            threat_number += 1
            threat = {
                "id": str(uuid.uuid4()),
                "title": title,
                "status": threat_status(state),
                "severity": priority,
                "type": category,
                "description": description,
                "mitigation": state_info,
                "modelType": "STRIDE",
                "new": False,
                "number": threat_number,
                "score": ""
            }
            flow_guid = child_text(value, "FlowGuid")
            source_guid = child_text(value, "SourceGuid")
            target_guid = child_text(value, "TargetGuid")
            destination_cell = guid_to_flow.get(flow_guid)
            if destination_cell is None:
                # Some custom threats may not reference a connector. Attach to
                # a matching component rather than silently discarding them.
                destination_cell = guid_to_node.get(target_guid) or guid_to_node.get(source_guid)
            if destination_cell is None:
                report.append(f"Threat '{title}' could not be attached to a converted flow or component.")
                continue
            threats_by_cell.setdefault(destination_cell["id"], []).append(threat)
    if total:
        report.append(f"Read {total} threat instances from the .tm7 file; {sum(len(v) for v in threats_by_cell.values())} were attached to diagram cells.")
    return threats_by_cell


def parse_threat_model(input_path):
    root = ET.parse(input_path).getroot()
    surface = next((e for e in root.iter() if local(e.tag) == "DrawingSurfaceModel"), None)
    if surface is None:
        raise ValueError("No DrawingSurfaceModel found in the .tm7 file.")

    cells, report = [], []
    guid_to_node, node_meta, guid_to_flow = {}, {}, {}
    boundary_boxes, boundary_curves = [], []
    z = 1
    borders = child(surface, "Borders")
    for entry in list(borders) if borders is not None else []:
        obj = child(entry, "Value")
        if obj is None:
            continue
        generic = child_text(obj, "GenericTypeId")
        type_id = child_text(obj, "TypeId")
        props = display_properties(obj)
        name = clean_name(props.get("Name", "")) or "Unnamed element"
        guid = child_text(obj, "Guid") or child_text(entry, "Key")
        x, y = number(obj, "Left"), number(obj, "Top")
        w, h = max(40, number(obj, "Width", 100)), max(40, number(obj, "Height", 70))
        out_of_scope = as_bool(props.get("Out Of Scope", "false"))
        description = props.get("Description", "")

        if generic.startswith("GE.TB"):
            data = {
                "type": "tm.BoundaryBox", "name": name, "description": description,
                "isTrustBoundary": True, "hasOpenThreats": False,
                "crossingFlows": [], "containedElements": []
            }
            boundary = make_node("trust-boundary-box", name, x, y, w, h, data, -1, include_ports=False)
            # Native Threat Dragon boundary boxes do not need ordinary node attrs.
            boundary.pop("attrs", None)
            cells.append(boundary)
            boundary_boxes.append({"guid": guid, "cell": boundary, "x": x, "y": y, "w": w, "h": h})
            continue

        if generic == "GE.P":
            shape, td_type = "process", "tm.Process"
        elif generic == "GE.DS":
            shape, td_type = "store", "tm.Store"
        elif generic == "GE.EI":
            shape, td_type = "actor", "tm.Actor"
        else:
            shape, td_type = "process", "tm.Process"
            report.append(f"Unknown element type '{type_id or generic}' ('{name}') mapped to a process.")
        data = {
            "type": td_type, "name": name, "description": description,
            "outOfScope": out_of_scope, "isTrustBoundary": False,
            "reasonOutOfScope": props.get("Reason For Out Of Scope", ""),
            "hasOpenThreats": False, "threats": []
        }
        if td_type == "tm.Process":
            data.update({"handlesCardPayment": False, "handlesGoodsOrServices": False,
                         "isWebApplication": "Web Application" in type_id, "privilegeLevel": ""})
        elif td_type == "tm.Store":
            data.update({"isALog": False, "isEncrypted": False, "isSigned": False,
                         "storesCredentials": False, "storesInventory": False})
        elif td_type == "tm.Actor":
            data.update({"providesAuthentication": False})
        node = make_node(shape, name, x, y, w, h, data, z)
        z += 1
        cells.append(node)
        guid_to_node[guid] = node
        node_meta[guid] = {"node": node, "ports": node["ports"], "x": x + w / 2,
                           "y": y + h / 2, "cx": x + w / 2, "cy": y + h / 2,
                           "x0": x, "y0": y, "w": w, "h": h, "name": name}

    lines = child(surface, "Lines")
    flow_records = []
    for entry in list(lines) if lines is not None else []:
        obj = child(entry, "Value")
        if obj is None:
            continue
        generic = child_text(obj, "GenericTypeId")
        type_id = child_text(obj, "TypeId")
        props = display_properties(obj)
        name = clean_name(props.get("Name", "")) or ("Trust Boundary" if generic == "GE.TB.L" else "Data Flow")
        guid = child_text(obj, "Guid") or child_text(entry, "Key")
        if generic == "GE.TB.L" or "Boundary" in type_id:
            sx, sy = number(obj, "SourceX"), number(obj, "SourceY")
            tx, ty = number(obj, "TargetX"), number(obj, "TargetY")
            hx, hy = child(obj, "HandleX"), child(obj, "HandleY")
            boundary_data = {"type": "tm.Boundary", "name": name,
                             "description": props.get("Description", ""),
                             "isTrustBoundary": True, "hasOpenThreats": False,
                             "crossingFlows": [], "containedElements": []}
            curve = {
                "shape": "trust-boundary-curve", "width": 200, "height": 100,
                "zIndex": 10, "connector": "smooth", "data": boundary_data,
                "labels": [name], "id": str(uuid.uuid4()),
                "source": {"x": round(sx), "y": round(sy)},
                "target": {"x": round(tx), "y": round(ty)}
            }
            if hx is not None and hy is not None:
                curve["vertices"] = [{"x": round(float(hx.text or 0)), "y": round(float(hy.text or 0))}]
            cells.append(curve)
            boundary_curves.append(curve)
            continue
        if generic != "GE.DF":
            report.append(f"Unknown line type '{type_id or generic}' ('{name}') skipped.")
            continue
        source_guid, target_guid = child_text(obj, "SourceGuid"), child_text(obj, "TargetGuid")
        source, target = node_meta.get(source_guid), node_meta.get(target_guid)
        if source is None or target is None:
            report.append(f"Flow '{name}' skipped because a source or target element could not be matched.")
            continue
        flow_data = {
            "type": "tm.Flow", "name": name, "description": props.get("Description", ""),
            "outOfScope": as_bool(props.get("Out Of Scope", "false")),
            "isTrustBoundary": False, "reasonOutOfScope": props.get("Reason For Out Of Scope", ""),
            "hasOpenThreats": False, "isBidirectional": False,
            "isEncrypted": as_bool(props.get("Encrypted", "false")),
            "isPublicNetwork": False, "protocol": props.get("Protocol", ""),
            "threats": [], "trustBoundaryIds": []
        }
        # SourceX/Y and TargetX/Y are actual connector endpoints; HandleX/Y is
        # Microsoft's bend handle. Use these rather than only node centres.
        sx, sy = number(obj, "SourceX", source["cx"]), number(obj, "SourceY", source["cy"])
        tx, ty = number(obj, "TargetX", target["cx"]), number(obj, "TargetY", target["cy"])
        hx, hy = child(obj, "HandleX"), child(obj, "HandleY")
        handle_x = float(hx.text) if hx is not None and hx.text else None
        handle_y = float(hy.text) if hy is not None and hy.text else None
        flow = make_flow(name, source, target, sx, sy, tx, ty, handle_x, handle_y, flow_data, 10)
        cells.append(flow)
        guid_to_flow[guid] = flow
        flow_records.append({"guid": guid, "source_guid": source_guid, "target_guid": target_guid,
                             "source": source, "target": target, "cell": flow})

    # Populate trust-boundary relationships using element centres and endpoint
    # membership. Threat Dragon uses these IDs for boundary crossing metadata.
    for boundary in boundary_boxes:
        x1, y1, x2, y2 = boundary["x"], boundary["y"], boundary["x"] + boundary["w"], boundary["y"] + boundary["h"]
        contained = []
        for guid, meta in node_meta.items():
            if x1 <= meta["cx"] <= x2 and y1 <= meta["cy"] <= y2:
                contained.append(meta["node"]["id"])
        boundary["cell"]["data"]["containedElements"] = contained
        for rec in flow_records:
            src_inside = x1 <= rec["source"]["cx"] <= x2 and y1 <= rec["source"]["cy"] <= y2
            tgt_inside = x1 <= rec["target"]["cx"] <= x2 and y1 <= rec["target"]["cy"] <= y2
            if src_inside != tgt_inside:
                boundary["cell"]["data"]["crossingFlows"].append(rec["cell"]["id"])
                rec["cell"]["data"]["trustBoundaryIds"].append(boundary["cell"]["id"])

    threats_by_cell = parse_threats(root, guid_to_flow, guid_to_node, report)
    for cell in cells:
        threats = threats_by_cell.get(cell["id"], [])
        if "data" in cell and isinstance(cell["data"], dict) and "threats" in cell["data"]:
            cell["data"]["threats"] = threats
            cell["data"]["hasOpenThreats"] = any(t["status"] == "Open" for t in threats)
            if cell["data"].get("type") == "tm.Process":
                freq = {"spoofing": 0, "tampering": 0, "repudiation": 0,
                        "informationDisclosure": 0, "denialOfService": 0, "elevationOfPrivilege": 0}
                keys = {"Spoofing": "spoofing", "Tampering": "tampering", "Repudiation": "repudiation",
                        "Information Disclosure": "informationDisclosure", "Denial of Service": "denialOfService",
                        "Elevation of Privilege": "elevationOfPrivilege"}
                for t in threats:
                    if t["type"] in keys:
                        freq[keys[t["type"]]] += 1
                cell["data"]["threatFrequency"] = freq

    threat_top= max (
        (t["number"] for c in cells for t in c.get("data", {}).get("threats",[])),
        default=0,
    ) + 1
    meta = next((e for e in root if local(e.tag) == "MetaInformation"), None)
    def meta_text(field, default=""):
        return child_text(meta, field, default) if meta is not None else default
    title = meta_text("ThreatModelName", Path(input_path).stem).strip() or Path(input_path).stem
    owner = meta_text("Owner", "").strip()
    description = meta_text("HighLevelSystemDescription", "").strip()
    diagram_title = "Diagram 1"
    props = child(surface, "Properties")
    if props is not None:
        for p in props:
            if child_text(p, "DisplayName") == "Name":
                val = child(p, "Value")
                if val is not None and val.text:
                    diagram_title = val.text
                    break

    result = {
        "version": "2.6.2",
        "summary": {"title": title, "owner": owner, "description": description, "id": 0},
        "detail": {
            "contributors": [],
            "diagrams": [{"id": 0, "title": diagram_title, "diagramType": "STRIDE",
                          "placeholder": "Converted from Microsoft Threat Modeling Tool",
                          "thumbnail": "./public/content/images/thumbnail.stride.jpg",
                          "version": "2.6.2", "cells": cells, "description": description}],
            "diagramTop": 1, "reviewer": meta_text("Reviewer", "").strip(), "threatTop": threat_top
        }
    }
    return result, report


def main():
    parser = argparse.ArgumentParser(description="Convert Microsoft Threat Modeling Tool .tm7 files to Threat Dragon 2.6.x JSON.")
    parser.add_argument("input", help="Input .tm7 file")
    parser.add_argument("-o", "--output", help="Output JSON file; defaults to INPUT.json")
    args = parser.parse_args()
    source = Path(args.input)
    output = Path(args.output) if args.output else source.with_suffix(".json")
    try:
        model, report = parse_threat_model(source)
        output.write_text(json.dumps(model, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
        cells = model["detail"]["diagrams"][0]["cells"]
        print(f"Converted model written to: {output}")
        print(f"Diagram cells: {len(cells)}")
        print(f"Threats attached: {sum(len(c.get('data', {}).get('threats', [])) for c in cells)}")
        if report:
            print("\nReview warnings:")
            for item in report:
                print(f"  - {item}")
        print("\nReview the generated diagram and threat details in Threat Dragon before relying on the conversion.")
    except (ET.ParseError, OSError, ValueError) as exc:
        print(f"Conversion failed: {exc}", file=sys.stderr)
        return 1
    return 0

if __name__ == "__main__":
    raise SystemExit(main())